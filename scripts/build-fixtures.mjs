#!/usr/bin/env node
// Reads schema/openapi.json and emits src/generated/fixtures.ts: one typed, named export per
// schema that carries an `example` (or the first entry of `examples`). These are the single
// source of deterministic sample data for MSW handlers and Storybook args — replacing orval's
// faker-based `mock: true` output, which ignores backend-declared examples entirely.
//
// Usage: node scripts/build-fixtures.mjs

import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const SCHEMA_PATH = fileURLToPath(
  new URL('../schema/openapi.json', import.meta.url),
);
const OUTPUT_PATH = fileURLToPath(
  new URL('../src/generated/fixtures.ts', import.meta.url),
);

// TEMPORARY: these schemas' declared `example` omits fields that are nullable-but-required
// (no Python-side default), because FastAPI drops null-valued keys when it renders a model's
// example into openapi.json. The backend fix (giving each field a `= None` default) is in
// PR #60, not yet deployed — remove this list once `npm run schema:sync` pulls a backend with
// that fix and these fixtures round-trip cleanly again.
const SKIP_SCHEMAS_PENDING_BACKEND_FIX = new Set([
  'DeletionRequestResponse',
  'ExportJobResponse',
  'InvitationResponse',
  'UserProfileResponse',
]);

function fixtureName(schemaName) {
  return `${schemaName[0].toLowerCase()}${schemaName.slice(1)}Fixture`;
}

async function main() {
  const schemaFile = await readFile(SCHEMA_PATH, 'utf-8');
  const schema = JSON.parse(schemaFile);
  const schemas = schema.components?.schemas ?? {};

  const skipped = [];
  const entries = Object.entries(schemas)
    .map(([name, def]) => {
      if (SKIP_SCHEMAS_PENDING_BACKEND_FIX.has(name)) {
        skipped.push(name);
        return null;
      }
      const example = def.example ?? def.examples?.[0];
      return example === undefined ? null : { name, example };
    })
    .filter(Boolean)
    .sort((a, b) => a.name.localeCompare(b.name));

  if (skipped.length > 0) {
    console.warn(
      `Skipped ${skipped.length} schema(s) pending backend fix (see SKIP_SCHEMAS_PENDING_BACKEND_FIX): ${skipped.join(', ')}`,
    );
  }

  const importedTypes = entries.map((e) => e.name);
  const lines = [];
  lines.push('/**');
  lines.push(
    ' * Generated by scripts/build-fixtures.mjs from schema/openapi.json examples.',
  );
  lines.push(
    ' * Do not edit manually — edit the backend Pydantic example, then re-run:',
  );
  lines.push(' *   npm run schema:sync && npm run fixtures:build');
  lines.push(' */');
  lines.push('');
  lines.push(`import type { ${importedTypes.join(', ')} } from './types';`);
  lines.push('');

  for (const { name, example } of entries) {
    lines.push(
      `export const ${fixtureName(name)}: ${name} = ${JSON.stringify(example, null, 2)};`,
    );
    lines.push('');
  }

  await writeFile(OUTPUT_PATH, `${lines.join('\n').trimEnd()}\n`);
  console.log(`Wrote ${entries.length} fixtures to ${OUTPUT_PATH}.`);
}

main().catch((err) => {
  console.error(err);
  process.exitCode = 1;
});
